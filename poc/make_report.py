#!/usr/bin/env python3
"""Build the PoC reports from the MAME captures (traces/poc) and the generated
code (build/gen). Re-runs compare_case for every case so the reports always
reflect the current build.

- poc/out/REPORT.md (ignored by Git): full report, including the original
  instructions and the generated C++. Derived from the game: keep it local.
- poc/SUMMARY.md (committed): bounds, case table and results only, with no
  game code and no translation of it.

usage: make_report.py [build_dir]
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GPR = ["zero", "at", "v0", "v1", "a0", "a1", "a2", "a3", "t0", "t1", "t2", "t3", "t4", "t5", "t6", "t7",
       "s0", "s1", "s2", "s3", "s4", "s5", "s6", "s7", "t8", "t9", "k0", "k1", "gp", "sp", "fp", "ra"]

FUNCS = {
    "8802d560": "checksum of a byte buffer [a0, a0+a1): 33-bit shift-register (LFSR-style) mixing with "
                "64-bit shifts; result in v0 (zero-extended 32 bits). Leaf, no stack, no stores, no I/O.",
    "880176f0": "single-precision FPU: reads two 2-D vectors from globals at 0x88035e30, computes the signed "
                "distance of a point from a line (mul/add/sub/div.s, c.eq.s/c.lt.s with bc1t/bc1f, sqrt.s, "
                "neg.s, cvt.w.s) and stores it, scaled, to a global. Leaf, 8-byte stack frame.",
    "8801a1e8": "single-precision FPU: from two integer points (v0,v1) and (a0,a1) computes the distance and "
                "the scaled unit vector, returned as integers in f0..f2 (cvt.s.w, sqrt.s, c.olt.s/bc1t, div.s, "
                "cvt.w.s); points closer than a threshold return f0 = 0. Leaf, no stack.",
    "8802d694": "fills the byte table at 0x88040e60 with 3 over [a0, a1); a loop branch targets the delay "
                "slot of the entry test (loop rotation). Leaf, no stack.",
    "8802d774": "compiled C, stack frame of 8 bytes: sums, over indices [a1, a2), either bit 0 (a0 == 1) "
                "or value >> 1 (otherwise) of the byte table at 0x88040e60; result in v0. Leaf, no I/O.",
}


def regs(path: Path) -> dict:
    return {k: int(v, 16) for k, v in (l.split() for l in path.read_text().splitlines())}


def function_blocks(gen_cpp: str, listing: str) -> dict:
    out = {}
    for m in re.finditer(r"function 0x([0-9a-f]{8})-0x([0-9a-f]{8}) \((\d+) insns\)\n((?:  .*\n)*)", listing):
        addr = m.group(1)
        code = re.search(rf"void func_{addr}\(ki::Context& c\) \{{\n.*?\n\}}\n", gen_cpp, re.S)
        out[addr] = (m.group(2), int(m.group(3)), m.group(4).rstrip(), code.group(0).rstrip() if code else "")
    return out


def main() -> int:
    build = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build"
    gen = (build / "gen/recompiled.cpp").read_text()
    listing = (build / "gen/recompiled.lst").read_text()
    blocks = function_blocks(gen, listing)
    sha = re.search(r"sha1 ([0-9a-f]{40})", gen).group(1)
    cases = sorted(p for p in (ROOT / "traces/poc").iterdir() if (p / "exit_regs.txt").exists())

    head = [f"- Game revision: Killer Instinct, MAME set `kinst`, BIOS `v1.5d`, U98 `ki-l15d.u98` "
          f"(SHA1 607394d4ba1713f38c2cb5159303cace9cde991e)",
          f"- Code image: `rom-0` unpacked from U98, loaded at 0x88000000, SHA1 {sha}",
          "- Reference: MAME 0.289 (Homebrew), original boot ROM + game code, captures via debugger breakpoints",
          "- Comparison: all 32 GPRs (64-bit), HI, LO, the low 32 bits of the 32 FPRs and FCSR (captures that include",
          "  COP1 state), return address, and every byte of SRAM (512 KiB) and DRAM (8 MiB)",
          ""]
    md = ["# PoC report: static recompilation of Killer Instinct (L1.5D) functions", "",
          "Generated by `poc/make_report.py`; do not edit by hand. **Contains original game code and its",
          "translation: local only, do not commit or publish.**", "", *head]
    pub = ["# PoC summary: static recompilation of Killer Instinct (L1.5D) functions", "",
           "Generated by `poc/make_report.py`; do not edit by hand. Contains no game code. The full report",
           "with the original instructions and the generated C++ is written to `poc/out/REPORT.md`",
           "(ignored by Git) when you run the proof with your own copy of the game.", "", *head]
    results = {}
    for c in cases:
        p = subprocess.run([str(build / "compare_case"), str(c)], capture_output=True, text=True)
        results[c.name] = (p.returncode == 0, p.stdout)

    for addr, (end, n, lst, code) in blocks.items():
        intro = [f"## Function 0x{addr}", "", FUNCS.get(addr, ""), "",
                 f"Bounds: 0x{addr}-0x{end} (exclusive), {n} instructions, found by the translator's linear scan "
                 "(first `jr $ra` not skipped by an internal forward branch).", ""]
        table = ["### Cases", "",
                 "| case | kind | MAME core | inputs | v0 MAME | v0 recomp | regs changed | memory written by the call | result |",
                 "|---|---|---|---|---|---|---|---|---|"]
        md += [*intro, "### Original instructions", "", "```", lst, "```", "",
               "### Generated C++ (automatic, `tools/kirecomp/kirecomp.py`, unedited)", "", "```cpp", code, "```", ""]
        rows = []
        for c in cases:
            meta = json.loads((c / "meta.json").read_text())
            if meta["function"] != addr:
                continue
            e, x = regs(c / "entry_regs.txt"), regs(c / "exit_regs.txt")
            ok, out = results[c.name]
            v0r = re.search(r"v0\s+\w+ -> \w+\s+recomp (\w+)", out)
            v0_recomp = v0r.group(1) if v0r else f"{x['v2' if False else 'v0']:016x}"
            changed = [r for r in GPR + ["hi", "lo"] if e[r] != x[r]]
            mem = re.findall(r"^\s+(sram|dram) (0x[0-9a-f]+-0x[0-9a-f]+) \((\d+) bytes\)", out.split("memory recomp")[0], re.M)
            mem_s = ", ".join(f"{a} {r} ({b} B)" for a, r, b in mem) or "none"
            kind = "synthetic (inputs injected)" if meta["inject"] else "real game call"
            disk = meta.get("disk", "blank")
            kind += f", {'blank disk' if disk == 'blank' else 'real disk'}"
            inputs = f"a0={e['a0']:x} a1={e['a1']:x} a2={e['a2']:x} ra={e['ra'] & 0xffffffff:x}"
            rows.append(f"| {c.name} | {kind} | {meta.get('mips3_core', 'drc')} | {inputs} | {x['v0']:x} | "
                      f"{int(v0_recomp, 16):x} | {', '.join(changed)} | {mem_s} | {'PASS' if ok else 'FAIL'} |")
        md += [*table, *rows, ""]
        pub += [*intro, *table, *rows, ""]

    passed = sum(ok for ok, _ in results.values())
    md += ["## Summary", "", f"{passed}/{len(results)} cases match MAME exactly.", "",
           "Full per-case output of `compare_case`:", ""]
    for name, (ok, out) in results.items():
        md += [f"<details><summary>{name}: {'PASS' if ok else 'FAIL'}</summary>", "", "```", out.rstrip(), "```",
               "", "</details>", ""]
    pub += ["## Summary", "", f"{passed}/{len(results)} cases match MAME exactly.", ""]
    (ROOT / "poc/out").mkdir(exist_ok=True)
    (ROOT / "poc/out/REPORT.md").write_text("\n".join(md))
    (ROOT / "poc/SUMMARY.md").write_text("\n".join(pub))
    print(f"wrote poc/SUMMARY.md and poc/out/REPORT.md ({passed}/{len(results)} pass)")
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    sys.exit(main())
